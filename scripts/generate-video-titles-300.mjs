function clean(s) {
  return String(s).replace(/\s+/g, " ").trim();
}

const seen = new Set();
const out = [];

function add(s) {
  const t = clean(s);
  if (!t) return;
  const key = t.toLowerCase();
  if (seen.has(key)) return;
  if ([...t].length > 90) return;
  seen.add(key);
  out.push(t);
}

for (const h of handcrafted) add(h);

// Combinatorial fillers to reach 300 with readable patterns
for (let a = 0; a < adj.length && out.length < 300; a++) {
  for (let n = 0; n < nouns.length && out.length < 300; n++) {
    add(`${adj[a]} ${nouns[n]}`);
    if (out.length >= 300) break;
    add(`${adj[a]} ${nouns[n]} ${tails[(a + n) % tails.length]}`);
    if (out.length >= 300) break;
    add(`${nouns[n]}: ${adj[a].toLowerCase()} mode`);
  }
}

// Last resort unique lines
let k = 1;
while (out.length < 300) {
  add(`Beauty moment ${k}`);
  k += 1;
  if (k > 200) break;
}

const final = out.slice(0, 300);
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outTxt, final.join("\n") + "\n", "utf8");
fs.writeFileSync(
  outCsv,
  "title\n" + final.map((t) => `"${t.replace(/"/g, '""')}"`).join("\n") + "\n",
  "utf8"
);

